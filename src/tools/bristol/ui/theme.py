"""ui/theme.py — the appearance package's single import point.

Every name it gives is defined in one of six modules and re-exported here
unchanged, so ``from .theme import C`` and ``from .theme import space`` keep
working for every module that imports them:

- ``ui/board_terms.py`` — the board's columns and card role, the fleet's agents
  and their captions, and the caption of every stored value.
- ``ui/tokens.py`` — spacing, corner radius, type size, window geometry and the
  scrim.
- ``ui/palettes.py`` — the palettes this build ships.
- ``ui/themes.py`` — schemes, themes and modes, the collection, contrast, and
  the live palette ``C``.
- ``ui/style_sheet.py`` — the typeface, the global stylesheet and
  ``apply_scheme()``.
- ``ui/ticket_log.py`` — a card's log and the timestamps it is shown with.

A change is made in the module that defines the name. These six import nothing
from the rest of the package at import time, so they and this module are the
safe bottom of the import graph.
"""

